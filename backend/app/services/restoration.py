"""
Advisory Restoration Prioritization and Switching Planner.
Generates safe, sequential isolation and back-feed switching sequences.
Strict safety constraints:
- Mark every plan "ADVISORY, requires qualified engineer review."
- Zero auto-execution: mandatory human dispatcher authorization.
- Zero unsafe sequences: Never route power into or energize an identified fault candidate section!
"""

from typing import Dict, List, Any, Optional
from sqlalchemy.orm import Session
import backend.app.models as m
from backend.app.graph_engine.engine import DistributionGraphEngine
from backend.app.services.asset_analysis import AssetAnalysisService

ADVISORY_DISCLAIMER = (
    "ADVISORY, requires qualified engineer review. Restoration switching instructions generated by "
    "FAULTTRACE AI are recommendations only. Physical verification of lockout/tagout (LOTO) protocols, "
    "field switch inspection, and human dispatcher authorization are mandatory prior to any physical operation. "
    "Never auto-execute."
)


class RestorationService:
    """Plans advisory restoration switching paths with transparent multi-criteria scoring."""

    def __init__(self, db: Session):
        self.db = db
        self.graph_engine = DistributionGraphEngine(db=db)
        self.asset_service = AssetAnalysisService(db=db)

    def plan_restoration(
        self,
        candidate_section_id: int,
        feeder_id: Optional[int] = None,
    ) -> Dict[str, Any]:
        """
        Generates a transparently-scored advisory switching plan to restore power
        while isolating the candidate fault section.
        """
        cand_meta = self.graph_engine.section_metadata.get(candidate_section_id)
        if not cand_meta:
            return {"error": f"Section ID {candidate_section_id} not found."}

        cand_code = cand_meta["section_code"]
        target_feeder_id = cand_meta["feeder_id"]
        target_feeder_code = cand_meta["feeder_code"]

        # 1. Analyze impacted assets downstream of fault candidate
        impact = self.asset_service.analyze_impact(candidate_section_id)
        downstream_sec_ids = set(self.graph_engine.get_downstream_sections(candidate_section_id))
        upstream_sec_ids = set(self.graph_engine.get_upstream_sections(candidate_section_id))

        # 2. Transparent Multi-Criteria Prioritization Scoring
        # Criteria Weights: Critical Loads (35%), Consumers (25%), Load kVA (20%), Severity (10%), Alternate Path (10%)
        crit_loads = impact.get("critical_facilities", [])
        has_t1 = any(cl["priority_tier"] == 1 for cl in crit_loads)
        has_t2 = any(cl["priority_tier"] == 2 for cl in crit_loads)
        crit_score = 35.0 if has_t1 else (20.0 if has_t2 else 5.0)

        consumers = impact.get("estimated_consumers_affected", 0)
        cons_score = min(25.0, (consumers / 400.0) * 25.0)

        load_kva = impact.get("total_interrupted_kva", 0.0)
        load_score = min(20.0, (load_kva / 500.0) * 20.0)

        sev = impact.get("severity_level", "LOW")
        sev_score = 10.0 if sev == "CRITICAL" else (7.0 if sev == "HIGH" else (4.0 if sev == "MEDIUM" else 2.0))

        # 3. Find candidate tie switches for alternate back-feed paths
        # Search connections linking any downstream section to an adjacent healthy feeder
        tie_connections = (
            self.db.query(m.NetworkConnection)
            .filter(
                m.NetworkConnection.is_tie_switch == True,
                (m.NetworkConnection.from_section_id.in_(downstream_sec_ids | {candidate_section_id}))
                | (m.NetworkConnection.to_section_id.in_(downstream_sec_ids | {candidate_section_id}))
            )
            .all()
        )

        viable_alternate_paths = []
        path_score = 0.0

        for tie in tie_connections:
            # Determine which side is the healthy donor feeder
            if tie.from_section_id in downstream_sec_ids or tie.from_section_id == candidate_section_id:
                donor_sec_id = tie.to_section_id
                transfer_sec_id = tie.from_section_id
            else:
                donor_sec_id = tie.from_section_id
                transfer_sec_id = tie.to_section_id

            donor_sec = self.db.query(m.FeederSection).filter_by(id=donor_sec_id).first()
            if not donor_sec:
                continue

            donor_feeder = donor_sec.feeder
            if donor_feeder.id == target_feeder_id:
                continue  # Same feeder cannot act as back-feed donor

            # Synthetic Capacity Check on Donor Feeder
            donor_capacity_kva = donor_feeder.nominal_capacity_mva * 1000.0  # MVA to kVA
            # Estimate current donor load (typically ~50-65% nominal)
            donor_current_load_kva = donor_capacity_kva * 0.55
            available_headroom_kva = donor_capacity_kva - donor_current_load_kva
            load_to_transfer_kva = load_kva

            is_within_capacity = load_to_transfer_kva <= available_headroom_kva
            capacity_utilization_after_transfer = round(
                ((donor_current_load_kva + load_to_transfer_kva) / donor_capacity_kva) * 100.0, 1
            )

            if is_within_capacity:
                path_score = 10.0

            viable_alternate_paths.append({
                "tie_switch_code": tie.switch_code,
                "donor_feeder_code": donor_feeder.feeder_code,
                "donor_feeder_name": donor_feeder.name,
                "donor_nominal_capacity_kva": donor_capacity_kva,
                "donor_available_headroom_kva": round(available_headroom_kva, 1),
                "load_to_transfer_kva": round(load_to_transfer_kva, 1),
                "capacity_check_passed": is_within_capacity,
                "projected_donor_utilization_pct": capacity_utilization_after_transfer,
                "connects_section_code": self.graph_engine.section_metadata[transfer_sec_id]["section_code"],
            })

        total_priority_score = round(crit_score + cons_score + load_score + sev_score + path_score, 1)

        # 4. Formulate Strictly Safe Sequential Switching Actions
        # SAFETY INVARIANT: Candidate fault section is strictly ISOLATED. NEVER ENERGIZED.
        switching_steps = []

        # Step 1: Physical Isolation of Candidate Fault Section
        switching_steps.append({
            "step_number": 1,
            "action_type": "ISOLATE_FAULT_SECTION",
            "device_code": f"AB-SW-ISO-{cand_code}",
            "target_section_code": cand_code,
            "operation": "OPEN",
            "advisory_notes": f"Physically isolate candidate fault section {cand_code}. Apply Lockout/Tagout (LOTO) safety tags.",
            "safety_rule": "MANDATORY: Candidate fault section must be isolated before restoring any adjacent sections.",
        })

        # Step 2: Upstream Trunk Re-energization (if healthy upstream sections exist)
        if upstream_sec_ids:
            first_upstream_code = self.graph_engine.section_metadata[list(upstream_sec_ids)[-1]]["section_code"]
            switching_steps.append({
                "step_number": 2,
                "action_type": "ENERGIZE_HEALTHY_UPSTREAM",
                "device_code": f"BRK-{target_feeder_code}",
                "target_section_code": first_upstream_code,
                "operation": "CLOSE",
                "advisory_notes": f"Close breaker BRK-{target_feeder_code} to re-energize healthy upstream trunk sections up to isolation boundary.",
                "safety_rule": f"VERIFY: Ensure isolation switch on {cand_code} is confirmed OPEN prior to breaker closing.",
            })

        # Step 3: Back-feed Downstream Branch via Alternate Tie-Switch (if available & capacity passes)
        best_tie = next((p for p in viable_alternate_paths if p["capacity_check_passed"]), None)
        if best_tie and downstream_sec_ids:
            switching_steps.append({
                "step_number": 3,
                "action_type": "CLOSE_TIE_SWITCH_BACKFEED",
                "device_code": best_tie["tie_switch_code"],
                "target_section_code": best_tie["connects_section_code"],
                "operation": "CLOSE",
                "advisory_notes": (
                    f"Close normally-open tie switch {best_tie['tie_switch_code']} to back-feed healthy downstream branch "
                    f"from donor Feeder {best_tie['donor_feeder_code']} ({best_tie['donor_feeder_name']}). "
                    f"Restores {len(impact['downstream_transformers'])} DTs and critical facility: "
                    f"{[c['facility_name'] for c in crit_loads]}."
                ),
                "safety_rule": f"VERIFY: Ensure candidate section {cand_code} is isolated so donor feeder cannot feed back into the fault.",
            })

        return {
            "candidate_section_id": candidate_section_id,
            "candidate_section_code": cand_code,
            "target_feeder_code": target_feeder_code,
            "restoration_priority_score": total_priority_score,
            "score_breakdown": {
                "critical_loads_score": crit_score,
                "consumers_score": round(cons_score, 1),
                "load_score": round(load_score, 1),
                "severity_score": sev_score,
                "alternate_path_score": path_score,
            },
            "advisory_disclaimer": ADVISORY_DISCLAIMER,
            "requires_engineer_approval": True,
            "approval_status": "PENDING_REVIEW",
            "alternate_paths_evaluated": viable_alternate_paths,
            "recommended_switching_steps": switching_steps,
            "estimated_restored_kva": round(load_kva, 1) if best_tie else 0.0,
            "estimated_restored_consumers": consumers if best_tie else 0,
        }
